import requests

BASE_URL = "https://api.open-meteo.com/v1/forecast"
GEO_URL = "https://geocoding-api.open-meteo.com/v1/search"

def get_weather(city):
    try:
        # Search for city coordinates
        geo_response = requests.get(
            GEO_URL,
            params={"name": city, "count": 1, "language": "en"},
            timeout=15
        )
        geo_response.raise_for_status()

        geo_data = geo_response.json()
        results = geo_data.get("results", [])

        if not results:
            print("City not found. Please try another city.")
            return None

        location = results[0]
        latitude = location["latitude"]
        longitude = location["longitude"]

        # Fetch current weather
        weather_response = requests.get(
            BASE_URL,
            params={
                "latitude": latitude,
                "longitude": longitude,
                "current": [
                    "temperature_2m",
                    "relative_humidity_2m",
                    "apparent_temperature",
                    "wind_speed_10m",
                    "weather_code"
                ]
            },
            timeout=15
        )
        weather_response.raise_for_status()

        data = weather_response.json()
        current = data["current"]

        weather_codes = {
            0: "Clear Sky",
            1: "Mainly Clear",
            2: "Partly Cloudy",
            3: "Overcast",
            45: "Foggy",
            48: "Depositing Rime Fog",
            51: "Light Drizzle",
            53: "Moderate Drizzle",
            55: "Dense Drizzle",
            61: "Slight Rain",
            63: "Moderate Rain",
            65: "Heavy Rain",
            71: "Slight Snow",
            73: "Moderate Snow",
            75: "Heavy Snow",
            80: "Rain Showers",
            81: "Moderate Rain Showers",
            82: "Heavy Rain Showers",
            95: "Thunderstorm"
        }

        code = current["weather_code"]

        weather = {
            "city": location["name"],
            "country": location.get("country", "Unknown"),
            "temperature": current["temperature_2m"],
            "feels_like": current["apparent_temperature"],
            "humidity": current["relative_humidity_2m"],
            "wind": current["wind_speed_10m"],
            "condition": weather_codes.get(code, "Other Conditions")
        }

        return weather

    except requests.exceptions.RequestException as error:
        print("Network/API error:", error)
    except (KeyError, ValueError, TypeError) as error:
        print("Unable to process weather data:", error)

    return None


def main():
    print("===== WEATHER APPLICATION =====")

    while True:
        print("\n1. Search Weather")
        print("2. Filter by Temperature")
        print("3. Exit")

        choice = input("Enter your choice: ").strip()

        if choice == "1":
            city = input("Enter city name: ").strip()

            if not city:
                print("Please enter a city name.")
                continue

            weather = get_weather(city)

            if weather:
                print("\n----- WEATHER REPORT -----")
                print("City:", weather["city"])
                print("Country:", weather["country"])
                print("Temperature:", weather["temperature"], "°C")
                print("Feels Like:", weather["feels_like"], "°C")
                print("Humidity:", weather["humidity"], "%")
                print("Wind Speed:", weather["wind"], "km/h")
                print("Condition:", weather["condition"])

        elif choice == "2":
            city = input("Enter city name: ").strip()

            try:
                limit = float(input("Enter maximum temperature (°C): "))

                weather = get_weather(city)

                if weather:
                    temperature = weather["temperature"]

                    print("\nCity:", weather["city"])
                    print("Current Temperature:", temperature, "°C")

                    if temperature <= limit:
                        print("Result: Temperature is within your limit.")
                    else:
                        print("Result: Temperature exceeds your limit.")

            except ValueError:
                print("Please enter a valid temperature.")

        elif choice == "3":
            print("Thank you for using the Weather Application!")
            break

        else:
            print("Invalid choice. Please try again.")


if __name__ == "__main__":
    main()