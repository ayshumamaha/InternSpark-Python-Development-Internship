import os
import shutil
import logging

# Create sample folder
folder = "MyFiles"
os.makedirs(folder, exist_ok=True)

# Create sample files automatically
samples = ["photo.jpg", "notes.txt", "report.pdf",
           "music.mp3", "empty.txt"]

for name in samples:
    path = os.path.join(folder, name)
    if not os.path.exists(path):
        open(path, "w").close()

# Create log file
logging.basicConfig(
    filename="automation.log",
    level=logging.INFO,
    format="%(asctime)s - %(message)s"
)

def sort_files():
    for file in os.listdir(folder):
        path = os.path.join(folder, file)

        if os.path.isfile(path):
            ext = os.path.splitext(file)[1].lower()
            category = {
                ".jpg": "Images",
                ".png": "Images",
                ".txt": "Documents",
                ".pdf": "Documents",
                ".mp3": "Audio"
            }.get(ext, "Others")

            destination = os.path.join(folder, category)
            os.makedirs(destination, exist_ok=True)

            shutil.move(path, os.path.join(destination, file))
            print(file, "moved to", category)
            logging.info("%s moved to %s", file, category)

def rename_files():
    files = [
        f for f in os.listdir(folder)
        if os.path.isfile(os.path.join(folder, f))
    ]

    for i, file in enumerate(files, 1):
        old = os.path.join(folder, file)
        ext = os.path.splitext(file)[1]
        new = os.path.join(folder, f"File_{i}{ext}")

        os.rename(old, new)
        print(file, "renamed to", os.path.basename(new))
        logging.info("%s renamed", file)

def clean_files():
    count = 0

    for file in os.listdir(folder):
        path = os.path.join(folder, file)

        if os.path.isfile(path) and os.path.getsize(path) == 0:
            os.remove(path)
            print(file, "deleted")
            logging.info("%s deleted", file)
            count += 1

    if count == 0:
        print("No empty files found.")

while True:
    print("\n===== PYTHON AUTOMATION =====")
    print("1. Sort Files")
    print("2. Rename Files")
    print("3. Clean Empty Files")
    print("4. Exit")

    choice = input("Enter your choice: ")

    try:
        if choice == "1":
            sort_files()
        elif choice == "2":
            rename_files()
        elif choice == "3":
            clean_files()
        elif choice == "4":
            print("Automation completed!")
            break
        else:
            print("Invalid choice!")

    except (OSError, PermissionError) as e:
        print("Error:", e)
        logging.error(str(e))