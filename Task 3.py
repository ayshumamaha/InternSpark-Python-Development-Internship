import pandas as pd

# Step 1: Create a sample dataset
data = {
    "Product": ["Laptop", "Mobile", "Tablet", "Laptop", "Mobile",
                "Tablet", "Laptop", "Mobile", "Tablet", "Laptop"],
    "Category": ["Electronics"] * 10,
    "Quantity": [2, 5, 3, 1, 4, 2, 3, 6, 1, 2],
    "Price": [50000, 15000, 20000, 50000, 15000,
              20000, 50000, 15000, 20000, 50000],
    "Sales": [100000, 75000, 60000, 50000, 60000,
              40000, 150000, 90000, 20000, 100000]
}

df = pd.DataFrame(data)

# Save dataset to CSV
df.to_csv("sales_data.csv", index=False)

print("===== ORIGINAL DATASET =====")
print(df)

# Step 2: Check and clean missing values
df = df.drop_duplicates()
df = df.fillna(0)

print("\n===== CLEANED DATASET =====")
print(df)

# Step 3: Summary statistics
print("\n===== SUMMARY STATISTICS =====")
print(df.describe())

# Step 4: Total sales
total_sales = df["Sales"].sum()
print("\nTotal Sales: Rs.", total_sales)

# Step 5: Product-wise sales
print("\n===== PRODUCT-WISE SALES =====")
product_sales = df.groupby("Product")["Sales"].sum()
print(product_sales)

# Step 6: Quantity sold by product
print("\n===== PRODUCT-WISE QUANTITY =====")
quantity = df.groupby("Product")["Quantity"].sum()
print(quantity)

# Step 7: Find the best-selling product
best_product = product_sales.idxmax()
print("\nBest-Selling Product:", best_product)

# Step 8: Find highest sales record
highest_sale = df.loc[df["Sales"].idxmax()]
print("\n===== HIGHEST SALES RECORD =====")
print(highest_sale)

# Step 9: Filter sales above Rs. 50,000
print("\n===== SALES ABOVE Rs. 50,000 =====")
print(df[df["Sales"] > 50000])

# Step 10: Final insights
print("\n===== FINAL INSIGHTS =====")
print("Total Number of Records:", len(df))
print("Total Sales: Rs.", total_sales)
print("Average Sales: Rs.", round(df["Sales"].mean(), 2))
print("Best-Selling Product:", best_product)

print("\nData Analysis Completed Successfully!")